/**
 * Dockerfiles for the `auto` strategy when neither Railpack nor Cloud Native
 * Buildpacks are installed. They are deliberately plain so that every app can
 * also be built without the framework (specification section 13.1, portability).
 */
import { LotseError, type Manifest } from "@lotse/core";
import type { ProjectInfo } from "./detect.js";

function shellForm(command: string): string {
  return `CMD ["sh", "-c", ${JSON.stringify(`exec ${command}`)}]`;
}

function nodeDockerfile(info: ProjectInfo, manifest: Manifest): string {
  const version = manifest.runtime.version ?? info.languageVersion ?? "22";
  const pm = info.packageManager ?? "npm";
  const setup = pm === "pnpm" || pm === "yarn" ? "RUN corepack enable\n" : pm === "bun" ? "RUN npm install -g bun\n" : "";
  const start = manifest.runtime.start ?? info.startCommand;
  if (!start) {
    throw new LotseError("BUILD_FAILED", "Cannot tell how to start this app: package.json has neither a start script nor a main entry.", {
      hints: ["Add `runtime.start` to lotse.yaml, for example `start: node server.js`."],
    });
  }
  const build = manifest.build.command ?? info.buildCommand;
  const prune = pm === "npm" ? "RUN npm prune --omit=dev\n" : pm === "pnpm" ? "RUN pnpm prune --prod\n" : "";
  return `# Generated by Lotse (build strategy: auto)
FROM node:${version}-alpine AS build
WORKDIR /app
${setup}COPY package.json package-lock.json* pnpm-lock.yaml* yarn.lock* bun.lock* ./
RUN ${info.installCommand ?? "npm install"}
COPY . .
${build ? `RUN ${build}\n` : ""}${prune}
FROM node:${version}-alpine
WORKDIR /app
ENV NODE_ENV=production PORT=${manifest.runtime.port}
${setup}COPY --from=build --chown=node:node /app /app
USER node
EXPOSE ${manifest.runtime.port}
${shellForm(start)}
`;
}

function pythonDockerfile(info: ProjectInfo, manifest: Manifest): string {
  const version = manifest.runtime.version ?? info.languageVersion ?? "3.13";
  const start = manifest.runtime.start ?? info.startCommand;
  if (!start) {
    throw new LotseError("BUILD_FAILED", "Cannot tell how to start this Python app.", {
      hints: ["Add `runtime.start` to lotse.yaml, for example `start: uvicorn main:app --host 0.0.0.0 --port $PORT`."],
    });
  }
  const build = manifest.build.command ?? (info.framework === "django" ? "python manage.py collectstatic --noinput" : undefined);
  return `# Generated by Lotse (build strategy: auto)
FROM python:${version}-slim
WORKDIR /app
ENV PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 PIP_NO_CACHE_DIR=1 PORT=${manifest.runtime.port}
COPY requirements.txt ./
RUN pip install -r requirements.txt
COPY . .
${build ? `RUN ${build}\n` : ""}RUN useradd --system --uid 10001 app && chown -R app /app
USER app
EXPOSE ${manifest.runtime.port}
${shellForm(start)}
`;
}

function goDockerfile(info: ProjectInfo, manifest: Manifest): string {
  const version = manifest.runtime.version ?? info.languageVersion ?? "1.27";
  return `# Generated by Lotse (build strategy: auto)
FROM golang:${version}-alpine AS build
WORKDIR /src
COPY go.mod go.sum* ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o /out/app .

FROM alpine:3
WORKDIR /app
ENV PORT=${manifest.runtime.port}
# Templates and static files live next to the binary.
COPY --from=build /src /app
COPY --from=build /out/app /app/app
RUN adduser -S -u 10001 app
USER app
EXPOSE ${manifest.runtime.port}
${shellForm(manifest.runtime.start ?? "/app/app")}
`;
}

function phpDockerfile(info: ProjectInfo, manifest: Manifest): string {
  const version = manifest.runtime.version ?? info.languageVersion ?? "8.4";
  const laravel = info.framework === "laravel";
  return `# Generated by Lotse (build strategy: auto)
FROM composer:2 AS vendor
WORKDIR /app
COPY . .
RUN composer install --no-dev --optimize-autoloader --no-interaction --ignore-platform-reqs

FROM dunglas/frankenphp:1-php${version}
WORKDIR /app
ENV SERVER_NAME=:${manifest.runtime.port} PORT=${manifest.runtime.port}
RUN install-php-extensions pdo_pgsql pdo_mysql opcache
COPY --from=vendor /app /app
${laravel ? "RUN chown -R www-data:www-data storage bootstrap/cache\n" : ""}EXPOSE ${manifest.runtime.port}
${manifest.runtime.start ? shellForm(manifest.runtime.start) : `CMD ["frankenphp", "php-server", "--root", "${laravel ? "public" : "."}", "--listen", ":${manifest.runtime.port}"]`}
`;
}

export function generateDockerfile(info: ProjectInfo, manifest: Manifest): string {
  const language = manifest.runtime.language ?? info.language;
  switch (language) {
    case "node":
      return nodeDockerfile(info, manifest);
    case "python":
      return pythonDockerfile(info, manifest);
    case "go":
      return goDockerfile(info, manifest);
    case "php":
      return phpDockerfile(info, manifest);
    default:
      throw new LotseError("BUILD_FAILED", `The auto build strategy does not know how to build "${language}" apps.`, {
        hints: ["Supported: node, python, go, php. Add a Dockerfile and set `build.strategy: dockerfile` for anything else."],
      });
  }
}

/** Port a packaged static site listens on unless PORT says otherwise. */
export const STATIC_IMAGE_PORT = 8080;

/** Serves a built static site from a small Caddy image; used where a target only runs containers. */
export function staticSiteDockerfile(): { dockerfile: string; caddyfile: string } {
  return {
    dockerfile: `# Generated by Lotse: static site packaged as a container
FROM caddy:2-alpine
ENV PORT=${STATIC_IMAGE_PORT}
COPY Caddyfile.lotse /etc/caddy/Caddyfile
COPY . /srv
RUN rm -f /srv/Caddyfile.lotse /srv/Dockerfile
EXPOSE ${STATIC_IMAGE_PORT}
`,
    caddyfile: `{
	admin off
	auto_https off
}
:{$PORT:${STATIC_IMAGE_PORT}} {
	root * /srv
	encode zstd gzip
	try_files {path} {path}/index.html {path}.html /index.html
	file_server
}
`,
  };
}
