export interface DnsRecord {
  type: "A" | "AAAA" | "CNAME" | "TXT" | "ALIAS";
  name: string;
  value: string;
}

export interface DomainStatus {
  domain: string;
  state: "active" | "pending" | "error";
  /** Records the user has to create at their DNS provider. */
  dnsRecords: DnsRecord[];
  message?: string;
}

export interface ResourceSpec {
  type: ResourceType;
  name: string;
  options?: Record<string, string>;
}

export interface ResourceRef {
  type: ResourceType;
  name: string;
  id: string;
  /** Adapter id that owns the resource. */
  provider: string;
  /** Connection values injected into the app, e.g. `DATABASE_URL`. */
  env: EnvVar[];
  meta?: Record<string, string>;
}

export interface ResourceStatus {
  state: "ready" | "creating" | "failed" | "not-found";
  message?: string;
}

export interface LogOptions {
  follow?: boolean;
  tail?: number;
  /** Epoch milliseconds. */
  since?: number;
  deployment?: string;
  signal?: AbortSignal;
}

export interface LogLine {
  at: number;
  stream: "stdout" | "stderr" | "system";
  line: string;
  source?: string;
}

export interface AppStatus {
  state: "running" | "deploying" | "stopped" | "failed" | "not-found" | "unknown";
  url?: string;
  domains: string[];
  deployment?: { id: string; createdAt?: number };
  message?: string;
}

// ---------------------------------------------------------------------------
// Hosting adapter
// ---------------------------------------------------------------------------

export interface HostingAdapter {
  readonly id: string;
  readonly displayName: string;
  readonly auth: AuthMethod[];
  readonly capabilities: Capabilities;

  /** OAuth metadata. Present when `auth` contains `"oauth"`. */
  readonly oauth?: OAuthProviderConfig;
  /** Guided token setup. Present when `auth` contains `"token"`. */
  readonly tokenSetup?: TokenSetupGuide;

  connect(input: ConnectInput): Promise<Connection>;
  /** Checks that the connection works and has the permissions deployments need. */
  verify(conn: Connection): Promise<VerifyResult>;

  plan(manifest: Manifest, conn: Connection): Promise<DeploymentPlan>;
  /**
   * Runs the deployment. The iterable MUST end with a `status` event for phase
   * `deploy` whose state is `succeeded` (carrying the `deployment`) or `failed`.
   * A failed or aborted deployment MUST leave the previously running version untouched.
   */
  deploy(plan: DeploymentPlan, artifact: BuildArtifact, ctx: DeployContext): AsyncIterable<DeployEvent>;
  /** Makes `target`, an earlier known-good deployment, the live version again. */
  rollback(target: DeploymentRef, ctx: DeployContext): Promise<void>;
  destroy(app: AppRef, ctx: DeployContext): Promise<void>;

  setEnv(app: AppRef, vars: EnvVar[]): Promise<void>;
  addDomain?(app: AppRef, domain: string): Promise<DomainStatus>;
  provision?(app: AppRef, res: ResourceSpec): Promise<ResourceRef>;
  logs(app: AppRef, opts: LogOptions): AsyncIterable<LogLine>;
  status(app: AppRef): Promise<AppStatus>;

  /** Present on adapters that can prepare a fresh server (specification section 10.2). */
  server?: ServerSetup;
  /** Present on adapters that run databases themselves (specification section 10.4). */
  backups?: BackupOperations;
}

export interface SetupStep {
  id: string;
  title: string;
  /** What the step changes on the server, shown before the user approves. */
  changes: string[];
  /** False when the server already is in the desired state. */
  needed: boolean;
  /** Set when the step cannot run on this system, with the reason. */
  skipped?: string;
}

export interface SetupPlan {
  host: string;
  os: { id: string; version: string; name: string; arch: string; supported: boolean };
  steps: SetupStep[];
  warnings: string[];
}

export interface ServerSetup {
  /** Inspects the server and lists what setup would change. Changes nothing. */
  planSetup(conn: Connection): Promise<SetupPlan>;
  /**
   * Applies the plan. The user MUST have approved it explicitly; without
   * `approved: true` the call is rejected with `APPROVAL_REQUIRED`.
   * Returns the connection to use from now on (the dedicated deployment user).
   */
  runSetup(conn: Connection, plan: SetupPlan, approval: { approved: boolean; signal?: AbortSignal }): AsyncGenerator<DeployEvent, Connection, void>;
}

export interface BackupInfo {
  id: string;
  resource: string;
  createdAt: number;
  bytes: number;
  location: "local" | "s3";
}

export interface BackupOperations {
  listBackups(app: AppRef, resource: string): Promise<BackupInfo[]>;
  createBackup(app: AppRef, resource: string): Promise<BackupInfo>;
  restoreBackup(app: AppRef, resource: string, backupId: string): Promise<void>;
}

// ---------------------------------------------------------------------------
// Resource adapter (specification section 7.4)
// ---------------------------------------------------------------------------

/**
 * Databases and storage. A resource adapter only implements `provision`,
 * `destroy` and `status` on top of the shared sign-in methods. The `AppRef`
 * passed to it carries the connection of the resource provider.
 */
export interface ResourceAdapter {
  readonly id: string;
  readonly displayName: string;
  readonly auth: AuthMethod[];
  readonly resources: ResourceType[];
  readonly oauth?: OAuthProviderConfig;
  readonly tokenSetup?: TokenSetupGuide;

  connect(input: ConnectInput): Promise<Connection>;
  verify(conn: Connection): Promise<VerifyResult>;

  provision(app: AppRef, res: ResourceSpec): Promise<ResourceRef>;
  destroy(app: AppRef, res: ResourceRef): Promise<void>;
  status(app: AppRef, res: ResourceRef): Promise<ResourceStatus>;
}

