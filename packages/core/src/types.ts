/**
 * Public adapter interface of the Lotse hosting core (specification section 7.2, 7.4, 11.5).
 *
 * The interface follows Semantic Versioning. `ADAPTER_API_VERSION` is bumped
 * whenever the interface changes; breaking changes only happen in a new major.
 */
import type { Manifest } from "./manifest.js";

export const ADAPTER_API_VERSION = "0.1.0";

// ---------------------------------------------------------------------------
// Sign-in
// ---------------------------------------------------------------------------

/** How a user can sign in to a provider. */
export type AuthMethod = "oauth" | "token" | "ssh";

export interface OAuthTokens {
  accessToken: string;
  refreshToken?: string;
  /** Unix epoch in milliseconds. */
  expiresAt?: number;
  scope?: string;
  tokenType?: string;
}

interface ConnectInputBase {
  /** Non-secret, adapter-specific settings such as `baseUrl`, `teamId` or `accountId`. */
  options?: Record<string, string>;
  /** Additional adapter-specific secrets, e.g. registry or backup storage credentials. Stored with the credentials. */
  secrets?: Record<string, string>;
}

export interface TokenConnectInput extends ConnectInputBase {
  method: "token";
  token: string;
}

export interface OAuthConnectInput extends ConnectInputBase {
  method: "oauth";
  tokens: OAuthTokens;
  /** The OAuth client the tokens were issued to; needed to refresh them later. */
  client?: OAuthClient;
}

export interface SshConnectInput extends ConnectInputBase {
  method: "ssh";
  host: string;
  port?: number;
  user?: string;
  /** OpenSSH private key. Generated by the framework unless supplied. */
  privateKey?: string;
  /** Only used once to install the framework's public key. Never stored. */
  password?: string;
  /** Pinned host key fingerprint (SHA256:...). Recorded on first connect. */
  hostKey?: string;
}

export type ConnectInput = TokenConnectInput | OAuthConnectInput | SshConnectInput;

/**
 * A signed-in provider account. Connections are plain data so they can be
 * stored in the encrypted credential store. `credentials` holds secret values
 * and MUST never be logged or handed to a language model.
 */
export interface Connection {
  adapter: string;
  method: AuthMethod;
  account: { id: string; name: string };
  credentials: Record<string, string>;
  settings: Record<string, string>;
  /** Expiry of the access token (epoch ms), if it expires. */
  expiresAt?: number;
}

export interface VerifyResult {
  ok: boolean;
  /** Human-readable account or server description. */
  account?: string;
  /** Permissions the framework needs for deployments but the connection lacks. */
  missingPermissions: string[];
  warnings: string[];
}

export interface OAuthClient {
  clientId: string;
  clientSecret?: string;
}

/** Static OAuth 2.0 metadata of a provider. The flow itself runs in the core. */
export interface OAuthProviderConfig {
  authorizationEndpoint: string;
  tokenEndpoint: string;
  /** RFC 7591 dynamic client registration endpoint, if the provider offers one. */
  registrationEndpoint?: string;
  scopes: string[];
  scopeSeparator?: string;
  /** Whether loopback redirects (RFC 8252) are accepted for native apps. */
  loopbackRedirect?: boolean;
  /** Extra query parameters for the authorization request. */
  extraAuthParams?: Record<string, string>;
  /** Environment variable prefix for operator-supplied clients, e.g. `LOTSE_OAUTH_VERCEL`. */
  envPrefix: string;
}

export interface SetupField {
  name: string;
  label: string;
  required: boolean;
  placeholder?: string;
  help?: string;
}

/** Guided token setup shown when OAuth is unavailable (specification section 8). */
export interface TokenSetupGuide {
  /** Direct link to the provider page where the token is created. */
  url: string;
  permissions: string[];
  steps: string[];
  /** Additional non-secret inputs, e.g. the base URL of a self-hosted instance. */
  fields?: SetupField[];
}

// ---------------------------------------------------------------------------
// Capabilities
// ---------------------------------------------------------------------------

export type RuntimeKind = "static" | "server" | "container";
export type ResourceType = "postgres" | "redis" | "object-storage" | (string & {});
export type RollbackSupport = "native" | "redeploy" | "none";

export interface Capabilities {
  runtimes: RuntimeKind[];
  languages: string[];
  resources: ResourceType[];
  customDomains: boolean;
  previewDeployments: boolean;
  rollback: RollbackSupport;
}

// ---------------------------------------------------------------------------
// Apps, deployments, artifacts
// ---------------------------------------------------------------------------

/**
 * Handle to an app at a provider. It carries the connection so that methods
 * such as `setEnv`, `logs` and `status` can authenticate.
 */
export interface AppRef {
  adapter: string;
  /** The manifest name; unique per connection. */
  name: string;
  /** Provider-side identifier, once the app exists. */
  id?: string;
  connection: Connection;
  meta?: Record<string, string>;
}

export interface DeploymentRef {
  id: string;
  app: AppRef;
  url?: string;
  createdAt: number;
  /** Provider-specific pointer to the deployed artifact (image tag, release id ...). */
  version?: string;
  /** Overrides how the engine verifies the deployment. Defaults to `url` + health check path. */
  probe?: { url: string; headers?: Record<string, string> };
  preview?: boolean;
  meta?: Record<string, string>;
}

export type ArtifactKind = "static" | "image" | "source";

export type BuildArtifact =
  | { kind: "static"; dir: string; files: number; bytes: number }
  | {
      kind: "image";
      image: string;
      digest?: string;
      platform: string;
      runtime: "docker" | "podman";
      port?: number;
    }
  | { kind: "source"; dir: string; ignore: string[] };

export interface PlanStep {
  id: string;
  title: string;
  detail?: string;
  action: "create" | "update" | "noop" | "delete";
  /** Steps that need explicit user approval (specification section 13.2). */
  critical?: boolean;
}

export interface PlannedResource {
  spec: ResourceSpec;
  /** Adapter id that provides the resource; equals the hosting adapter for native resources. */
  provider: string;
  native: boolean;
  action: "create" | "reuse";
}

export interface DeploymentPlan {
  adapter: string;
  app: AppRef;
  manifest: Manifest;
  /** The artifact the adapter needs from the build step. */
  artifact: ArtifactKind;
  firstDeployment: boolean;
  steps: PlanStep[];
  resources: PlannedResource[];
  warnings: string[];
  /** Adapter-private data carried from `plan` to `deploy`. */
  meta?: Record<string, unknown>;
}

export interface EnvVar {
  name: string;
  value: string;
  secret: boolean;
}

export interface DeployContext {
  connection: Connection;
  /** Project directory containing the source code. */
  workdir: string;
  /** Fully resolved environment (public values, secrets, resource connection strings). */
  env: EnvVar[];
  /** Resources provisioned for this app. */
  resources: ResourceRef[];
  /** Last successful deployment, if any. */
  previous?: DeploymentRef;
  /** Set for preview deployments of pull or merge requests. */
  preview?: { id: string; branch?: string };
  /** The Git repository the project is linked to, for providers that build from Git themselves. */
  repository?: { url: string; branch: string; commit?: string };
  signal?: AbortSignal;
}

// ---------------------------------------------------------------------------
// Events
// ---------------------------------------------------------------------------

export type DeployPhase = "plan" | "build" | "provision" | "deploy" | "verify" | "rollback" | "finish";

export interface StatusEvent {
  type: "status";
  phase: DeployPhase;
  state: "started" | "succeeded" | "failed" | "skipped";
  message?: string;
  /** Present on the final `deploy`/`finish` status events. */
  deployment?: DeploymentRef;
  at: number;
}

export interface ProgressEvent {
  type: "progress";
  phase: DeployPhase;
  current: number;
  total?: number;
  message?: string;
  at: number;
}

export interface LogEvent {
  type: "log";
  phase: DeployPhase;
  stream: "stdout" | "stderr" | "system";
  line: string;
  at: number;
}

export interface ErrorEvent {
  type: "error";
  phase: DeployPhase;
  code: string;
  message: string;
  at: number;
}

export type DeployEvent = StatusEvent | ProgressEvent | LogEvent | ErrorEvent;

