// Git provider (specification section 11.5)
// ---------------------------------------------------------------------------

export interface RepoRef {
  provider: string;
  owner: string;
  name: string;
  id?: string;
  defaultBranch: string;
  private: boolean;
  /** Browser URL of the repository. */
  url: string;
  /** HTTPS clone URL without credentials. */
  cloneUrl: string;
  /**
   * The connection the repository was obtained with. `listRepos` and
   * `createRepo` set it; callers restoring a stored `RepoRef` set it again so
   * that `setCiSecret`, `writeWorkflow` and `comment` can authenticate.
   * It is stripped before a `RepoRef` is persisted (see `toRepoRecord`).
   */
  connection?: Connection;
}

export type RepoRecord = Omit<RepoRef, "connection">;

export interface RepoSpec {
  name: string;
  /** Organization or group; defaults to the signed-in user. */
  owner?: string;
  private: boolean;
  description?: string;
  /** Create an initial commit on the default branch, so that the repository is not empty. */
  initialize?: boolean;
}

/** Clone URL plus the credentials Git needs. Credentials are never written into the URL. */
export interface AuthenticatedUrl {
  url: string;
  username: string;
  password: string;
  expiresAt?: number;
}

/** A hosting target a generated CI workflow deploys to. */
export interface HostingTarget {
  /** Hosting adapter id, e.g. `ssh`. */
  adapter: string;
  /** Branch whose pushes trigger a deployment. */
  branch: string;
  /** Names of the CI secrets the workflow passes to the CLI. */
  secrets: string[];
  /** Version of `@lotseai/cli` the workflow installs. */
  cliVersion?: string;
  /** Whether to deploy previews for pull or merge requests. */
  previews?: boolean;
}

export interface GitProvider {
  readonly id: string;
  readonly displayName: string;
  readonly auth: AuthMethod[];
  readonly oauth?: OAuthProviderConfig;
  readonly tokenSetup?: TokenSetupGuide;

  connect(input: ConnectInput): Promise<Connection>;
  listRepos(conn: Connection, query?: string): Promise<RepoRef[]>;
  createRepo(conn: Connection, spec: RepoSpec): Promise<RepoRef>;
  remoteUrl(repo: RepoRef, conn: Connection): Promise<AuthenticatedUrl>;
  setCiSecret?(repo: RepoRef, name: string, value: string): Promise<void>;
  writeWorkflow?(repo: RepoRef, target: HostingTarget): Promise<void>;
  comment?(repo: RepoRef, request: number, body: string): Promise<void>;
  /** Pages as a hosting target for static sites. */
  pages?: HostingAdapter;
}

