export interface AdapterOptions {
  /** HTTP transport. Contract tests inject a replaying implementation. */
  fetch?: typeof fetch;
  /** Process environment, used for operator-supplied OAuth clients. */
  env?: Record<string, string | undefined>;
  /** Adapter-specific settings from the instance configuration. */
  settings?: Record<string, unknown>;
  /** Pushes and exports container images. Defaults to the Docker or Podman CLI. */
  images?: import("./images.js").ImageTools;
}

/**
 * Default export of an adapter package (`@lotseai/adapter-*` or `lotse-adapter-*`).
 */
export interface AdapterPackage {
  apiVersion: string;
  hosting?: (options?: AdapterOptions) => HostingAdapter;
  git?: (options?: AdapterOptions) => GitProvider;
  resource?: (options?: AdapterOptions) => ResourceAdapter;
}

/**
 * Name of the environment variable a resource's connection string is injected
 * as. Shared by all adapters so that an app does not change when it moves.
 */
export function resourceEnvName(type: ResourceType, name: string): string {
  const upper = name.toUpperCase().replace(/-/g, "_");
  if (type === "postgres") return name === "db" || name === "database" ? "DATABASE_URL" : `${upper}_DATABASE_URL`;
  if (type === "redis") return name === "redis" || name === "cache" ? "REDIS_URL" : `${upper}_REDIS_URL`;
  return `${upper}_URL`;
}
