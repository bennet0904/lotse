/**
 * CI definitions that call the CLI (specification section 11.1, "CI pipeline").
 * They make push-to-deploy work for targets without their own Git integration,
 * such as an own server. Credentials are read from secrets on the platform.
 */
import type { HostingTarget } from "./types.js";

export const WORKFLOW_NAME = "lotse-deploy.yml";

/** Name of the CI secret that holds the exported connection for an adapter. */
export function connectionSecretName(adapter: string): string {
  return `LOTSE_CONNECTION_${adapter.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`;
}

function cliCommand(target: HostingTarget, extra = ""): string {
  const pkg = target.cliVersion ? `@lotse/cli@${target.cliVersion}` : "@lotse/cli";
  return `npx --yes ${pkg} deploy --target ${target.adapter} --yes${extra}`;
}

/** Workflow for GitHub Actions. Forgejo and Gitea Actions understand the same syntax. */
export function actionsWorkflow(target: HostingTarget, flavor: "github" | "forgejo" = "github"): string {
  const ctx = flavor === "github" ? "github" : "forge";
  const secrets = target.secrets.map((s) => `          ${s}: \${{ secrets.${s} }}`).join("\n");
  const previews = target.previews
    ? `
  preview:
    if: ${ctx}.event_name == 'pull_request'
    runs-on: ubuntu-latest
    permissions:
      contents: read
      pull-requests: write
    steps:
      - uses: actions/checkout@v5
      - uses: actions/setup-node@v5
        with:
          node-version: 22
      - name: Deploy preview
        run: ${cliCommand(target, ` --preview pr-\${{ ${ctx}.event.pull_request.number }} --comment \${{ ${ctx}.event.pull_request.number }}`)}
        env:
${secrets}
          LOTSE_GIT_TOKEN: \${{ secrets.GITHUB_TOKEN }}
`
    : "";
  return `# Generated by Lotse. Deploys every push to ${target.branch} with the Lotse CLI.
# Edit freely; \`lotse git ci\` only rewrites this file when asked to.
name: Deploy with Lotse

on:
  push:
    branches: [${target.branch}]
${target.previews ? "  pull_request:\n" : ""}  workflow_dispatch:

concurrency:
  group: lotse-deploy-\${{ ${ctx}.ref }}
  cancel-in-progress: false

permissions:
  contents: read

jobs:
  deploy:
    if: ${ctx}.event_name != 'pull_request'
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v5
      - uses: actions/setup-node@v5
        with:
          node-version: 22
      - name: Deploy
        run: ${cliCommand(target)}
        env:
${secrets}
${previews}`;
}

/** Pipeline for GitLab CI/CD. */
export function gitlabPipeline(target: HostingTarget): string {
  const previews = target.previews
    ? `
lotse-preview:
  stage: deploy
  image: node:22
  script:
    - ${cliCommand(target, " --preview mr-$CI_MERGE_REQUEST_IID --comment $CI_MERGE_REQUEST_IID")}
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
`
    : "";
  return `# Generated by Lotse. Deploys every push to ${target.branch} with the Lotse CLI.
# Secrets (${target.secrets.join(", ")}) are masked CI/CD variables of the project.
stages:
  - deploy

lotse-deploy:
  stage: deploy
  image: node:22
  services:
    - docker:dind
  variables:
    DOCKER_HOST: tcp://docker:2375
    DOCKER_TLS_CERTDIR: ""
  before_script:
    - apt-get update -qq && apt-get install -y -qq docker.io >/dev/null
  script:
    - ${cliCommand(target)}
  resource_group: lotse-deploy
  rules:
    - if: $CI_COMMIT_BRANCH == "${target.branch}"
${previews}`;
}

/** Pipeline that publishes a branch of static files with GitLab Pages. */
export function gitlabPagesPipeline(): string {
  return `# Generated by Lotse: publishes this branch with GitLab Pages.
pages:
  stage: deploy
  image: alpine:3
  script:
    - mkdir .public
    - cp -r ./* .public/
    - mv .public public
  artifacts:
    paths:
      - public
  rules:
    - if: $CI_COMMIT_BRANCH
`;
}
