/**
 * Setting up a new server (specification section 10.2). Every step is
 * idempotent: running the setup again leads to the same result.
 */
import { type Connection, type DeployEvent, event, LotseError, type SetupPlan, type SetupStep } from "@lotse/core";
import { must, paramsOf, publicKeyOf, type SshConnector, type SshExecutor, sh } from "./executor.js";
import { DEPLOY_USER, mainCaddyfile, NETWORK, PROXY, PROXY_IMAGE, ROOT } from "./layout.js";

export interface ServerFacts {
  id: string;
  version: string;
  name: string;
  codename: string;
  arch: string;
  uid: number;
  sudo: boolean;
  systemd: boolean;
  docker: string;
  dockerAccess: boolean;
  deployUser: boolean;
  deployKey: boolean;
  proxy: boolean;
  firewall: boolean;
  updates: boolean;
  backupTimer: boolean;
}

function detectScript(publicKey: string): string {
  return `
. /etc/os-release 2>/dev/null || true
home=$(getent passwd ${DEPLOY_USER} 2>/dev/null | cut -d: -f6 || true)
echo "id=\${ID:-unknown}"
echo "version=\${VERSION_ID:-}"
echo "name=\${PRETTY_NAME:-unknown}"
echo "codename=\${VERSION_CODENAME:-}"
echo "arch=$(uname -m)"
echo "uid=$(id -u)"
echo "systemd=$([ -d /run/systemd/system ] && echo yes || echo no)"
echo "docker=$(command -v docker >/dev/null 2>&1 && (docker version --format '{{.Server.Version}}' 2>/dev/null || echo stopped) || echo missing)"
echo "dockerAccess=$(docker info >/dev/null 2>&1 && echo yes || echo no)"
echo "deployUser=$(id -u ${DEPLOY_USER} >/dev/null 2>&1 && echo yes || echo no)"
echo "deployKey=$([ -n "$home" ] && grep -qF ${sh(publicKey.split(" ").slice(0, 2).join(" "))} "$home/.ssh/authorized_keys" 2>/dev/null && echo yes || echo no)"
echo "proxy=$([ "$(docker inspect -f '{{.State.Running}}' ${PROXY} 2>/dev/null || true)" = true ] && echo yes || echo no)"
echo "firewall=$(grep -qs '^ENABLED=yes' /etc/ufw/ufw.conf && echo yes || echo no)"
echo "updates=$(grep -qs 'Unattended-Upgrade "1"' /etc/apt/apt.conf.d/20auto-upgrades && echo yes || echo no)"
echo "backupTimer=$([ -x ${ROOT}/bin/lotse-backup ] && echo yes || echo no)"
`;
}

export async function detectServer(executor: SshExecutor, publicKey: string): Promise<ServerFacts> {
  const probe = await executor.run("probe-sudo", `[ "$(id -u)" = 0 ] && echo root || (sudo -n true 2>/dev/null && echo sudo || echo none)`);
  const privilege = probe.stdout.trim();
  const out = await must(executor, "detect", detectScript(publicKey), { sudo: privilege === "sudo" });
  const facts = Object.fromEntries(
    out
      .split("\n")
      .filter((l) => l.includes("="))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()]),
  );
  return {
    id: facts.id ?? "unknown",
    version: facts.version ?? "",
    name: facts.name ?? "unknown",
    codename: facts.codename ?? "",
    arch: facts.arch ?? "x86_64",
    uid: Number(facts.uid ?? 1),
    sudo: privilege === "root" || privilege === "sudo",
    systemd: facts.systemd === "yes",
    docker: facts.docker ?? "missing",
    dockerAccess: facts.dockerAccess === "yes",
    deployUser: facts.deployUser === "yes",
    deployKey: facts.deployKey === "yes",
    proxy: facts.proxy === "yes",
    firewall: facts.firewall === "yes",
    updates: facts.updates === "yes",
    backupTimer: facts.backupTimer === "yes",
  };
}

/** Ubuntu 24.04 LTS and later, Debian 12 and later (specification section 10.1). */
export function isSupportedOs(id: string, version: string): boolean {
  const major = Number.parseFloat(version);
  return (id === "ubuntu" && major >= 24.04) || (id === "debian" && major >= 12);
}

export function platformOf(arch: string): string {
  return arch === "aarch64" || arch === "arm64" ? "linux/arm64" : "linux/amd64";
}

export interface SetupSettings {
  sshPort: number;
  httpPort: number;
  httpsPort: number;
  acmeEmail?: string;
}

export function buildSetupPlan(host: string, facts: ServerFacts, settings: SetupSettings): SetupPlan {
  const supported = isSupportedOs(facts.id, facts.version);
  const manual = supported ? undefined : `Automatic setup is only available on Ubuntu 24.04+ and Debian 12+ (found ${facts.name}).`;
  const warnings: string[] = [];
  if (!supported) warnings.push(`${facts.name} is not a supported system. Docker must already be installed; firewall and security updates stay as they are.`);
  if (settings.sshPort !== 22) warnings.push(`SSH runs on port ${settings.sshPort}. The firewall will keep that port open instead of 22.`);

  const steps: SetupStep[] = [
    {
      id: "user",
      title: `Create the deployment user "${DEPLOY_USER}"`,
      changes: [`Adds the user ${DEPLOY_USER} without a password`, `Installs the SSH key generated by Lotse in ~${DEPLOY_USER}/.ssh/authorized_keys`],
      needed: !facts.deployUser || !facts.deployKey,
    },
    {
      id: "docker",
      title: "Install Docker Engine",
      changes: [
        "Adds Docker's official package repository (download.docker.com)",
        "Installs docker-ce, containerd and the buildx plugin",
        `Adds ${DEPLOY_USER} to the docker group`,
      ],
      needed: facts.docker === "missing" || !facts.deployUser,
      skipped: !supported && facts.docker === "missing" ? manual : undefined,
    },
    {
      id: "proxy",
      title: "Start Caddy as reverse proxy",
      changes: [
        `Creates ${ROOT} and the Docker network "${NETWORK}"`,
        `Starts the container ${PROXY} (${PROXY_IMAGE}) on ports ${settings.httpPort} and ${settings.httpsPort}`,
        "Caddy obtains TLS certificates automatically from Let's Encrypt",
      ],
      needed: !facts.proxy,
    },
    {
      id: "firewall",
      title: "Configure the firewall",
      changes: [`Installs ufw and denies incoming traffic except ports ${settings.sshPort} (SSH), 80 and 443`],
      needed: !facts.firewall,
      skipped: manual,
    },
    {
      id: "updates",
      title: "Enable automatic security updates",
      changes: ["Installs unattended-upgrades and enables daily security updates"],
      needed: !facts.updates,
      skipped: manual,
    },
    {
      id: "backups",
      title: "Schedule daily database backups",
      changes: [
        `Installs ${ROOT}/bin/lotse-backup`,
        facts.systemd ? "Adds a systemd timer that runs it every night" : "No systemd found: backups run only when triggered manually",
      ],
      needed: !facts.backupTimer,
    },
  ];
  return {
    host,
    os: { id: facts.id, version: facts.version, name: facts.name, arch: facts.arch, supported },
    steps,
    warnings,
  };
}

const APT = "export DEBIAN_FRONTEND=noninteractive";

export const BACKUP_SCRIPT = `#!/usr/bin/env bash
# Managed by Lotse: dumps every Postgres database that runs as a Lotse resource.
set -euo pipefail
ROOT=${ROOT}
KEEP=\${LOTSE_KEEP_BACKUPS:-14}
only_app="\${1:-}"
only_res="\${2:-}"
[ -f "$ROOT/backup.env" ] && . "$ROOT/backup.env"
stamp=$(date -u +%Y%m%dT%H%M%SZ)
docker ps --filter label=dev.lotse.resource --format '{{.Names}} {{.Label "dev.lotse.app"}} {{.Label "dev.lotse.resource-name"}} {{.Label "dev.lotse.resource"}}' | while read -r container app res type; do
  [ -n "$only_app" ] && [ "$app" != "$only_app" ] && continue
  [ -n "$only_res" ] && [ "$res" != "$only_res" ] && continue
  dir="$ROOT/backups/$app/$res"
  mkdir -p "$dir"
  case "$type" in
    postgres)
      file="$dir/$stamp.sql.gz"
      docker exec "$container" sh -c 'pg_dump --clean --if-exists -U "$POSTGRES_USER" "$POSTGRES_DB"' | gzip > "$file.tmp"
      ;;
    redis)
      file="$dir/$stamp.rdb.gz"
      docker exec "$container" sh -c 'redis-cli -a "$REDIS_PASSWORD" --no-auth-warning save >/dev/null && cat /data/dump.rdb' | gzip > "$file.tmp"
      ;;
    *) continue ;;
  esac
  mv "$file.tmp" "$file"
  echo "$file"
  if [ -n "\${S3_BUCKET:-}" ]; then
    docker run --rm -v "$dir:/backup:ro" curlimages/curl:latest -fsS --aws-sigv4 "aws:amz:\${S3_REGION:-us-east-1}:s3" \\
      --user "$S3_ACCESS_KEY:$S3_SECRET_KEY" -T "/backup/$(basename "$file")" "\${S3_ENDPOINT%/}/$S3_BUCKET/$app/$res/$(basename "$file")" >/dev/null
  fi
  ls -1t "$dir" | grep -v '\\.tmp$' | tail -n +$((KEEP + 1)) | while read -r old; do rm -f "$dir/$old"; done
done
`;

function stepScripts(settings: SetupSettings, publicKey: string): Record<string, { script: string; stdin?: string }> {
  return {
    user: {
      stdin: `${publicKey}\n`,
      script: `
read -r KEY
if ! id -u ${DEPLOY_USER} >/dev/null 2>&1; then
  if command -v useradd >/dev/null 2>&1; then useradd --create-home --shell /bin/bash ${DEPLOY_USER}; else adduser -D -s /bin/sh ${DEPLOY_USER}; fi
fi
# No password, but not locked: key-based logins must work.
command -v usermod >/dev/null 2>&1 && usermod -p '*' ${DEPLOY_USER} || true
home=$(getent passwd ${DEPLOY_USER} | cut -d: -f6)
install -d -m 700 -o ${DEPLOY_USER} -g "$(id -gn ${DEPLOY_USER})" "$home/.ssh"
touch "$home/.ssh/authorized_keys"
grep -qxF "$KEY" "$home/.ssh/authorized_keys" || echo "$KEY" >> "$home/.ssh/authorized_keys"
chown ${DEPLOY_USER} "$home/.ssh/authorized_keys"
chmod 600 "$home/.ssh/authorized_keys"
echo "user ${DEPLOY_USER} ready"
`,
    },
    docker: {
      script: `
${APT}
if ! command -v docker >/dev/null 2>&1; then
  . /etc/os-release
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl >/dev/null
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL "https://download.docker.com/linux/$ID/gpg" -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/$ID $VERSION_CODENAME stable" > /etc/apt/sources.list.d/docker.list
  apt-get update -qq
  apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin >/dev/null
  echo "installed $(docker --version)"
fi
[ -d /run/systemd/system ] && systemctl enable --now docker >/dev/null 2>&1 || true
getent group docker >/dev/null || groupadd docker
if command -v usermod >/dev/null 2>&1; then usermod -aG docker ${DEPLOY_USER}; else addgroup ${DEPLOY_USER} docker; fi
for i in $(seq 1 60); do docker info >/dev/null 2>&1 && break; sleep 1; done
docker info >/dev/null
echo "docker $(docker version --format '{{.Server.Version}}') is running"
`,
    },
    proxy: {
      stdin: mainCaddyfile(settings.acmeEmail),
      script: `
group=$(id -gn ${DEPLOY_USER})
for d in "" /apps /caddy /caddy/conf /caddy/conf/sites /caddy/data /caddy/config /backups /bin; do install -d -m 755 -o ${DEPLOY_USER} -g "$group" "${ROOT}$d"; done
docker network inspect ${NETWORK} >/dev/null 2>&1 || docker network create ${NETWORK} >/dev/null
if [ -f ${ROOT}/caddy/conf/Caddyfile ]; then cat >/dev/null; else cat > ${ROOT}/caddy/conf/Caddyfile; chown ${DEPLOY_USER} ${ROOT}/caddy/conf/Caddyfile; fi
if docker inspect ${PROXY} >/dev/null 2>&1; then
  docker start ${PROXY} >/dev/null
else
  docker run -d --name ${PROXY} --restart unless-stopped --network ${NETWORK} \\
    -p ${settings.httpPort}:80 -p ${settings.httpsPort}:443 -p ${settings.httpsPort}:443/udp \\
    -v ${ROOT}/caddy/conf:/etc/caddy:ro -v ${ROOT}/caddy/data:/data -v ${ROOT}/caddy/config:/config -v ${ROOT}/apps:/srv/apps:ro \\
    --label dev.lotse.role=proxy ${PROXY_IMAGE} >/dev/null
fi
for i in $(seq 1 30); do [ "$(docker inspect -f '{{.State.Running}}' ${PROXY})" = true ] && break; sleep 1; done
[ "$(docker inspect -f '{{.State.Running}}' ${PROXY})" = true ]
echo "caddy is running"
`,
    },
    firewall: {
      script: `
${APT}
command -v ufw >/dev/null 2>&1 || { apt-get update -qq; apt-get install -y -qq ufw >/dev/null; }
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw allow ${settings.sshPort}/tcp >/dev/null
ufw allow 80/tcp >/dev/null
ufw allow 443/tcp >/dev/null
ufw allow 443/udp >/dev/null
ufw --force enable >/dev/null
ufw status | head -1
`,
    },
    updates: {
      script: `
${APT}
dpkg -s unattended-upgrades >/dev/null 2>&1 || { apt-get update -qq; apt-get install -y -qq unattended-upgrades >/dev/null; }
printf 'APT::Periodic::Update-Package-Lists "1";\\nAPT::Periodic::Unattended-Upgrade "1";\\n' > /etc/apt/apt.conf.d/20auto-upgrades
[ -d /run/systemd/system ] && systemctl enable --now unattended-upgrades >/dev/null 2>&1 || true
echo "automatic security updates enabled"
`,
    },
    backups: {
      stdin: BACKUP_SCRIPT,
      script: `
install -d -m 755 -o ${DEPLOY_USER} ${ROOT}/bin ${ROOT}/backups
cat > ${ROOT}/bin/lotse-backup
chmod 755 ${ROOT}/bin/lotse-backup
chown ${DEPLOY_USER} ${ROOT}/bin/lotse-backup
if [ -d /run/systemd/system ]; then
  printf '[Unit]\\nDescription=Lotse database backups\\nAfter=docker.service\\n\\n[Service]\\nType=oneshot\\nUser=${DEPLOY_USER}\\nExecStart=${ROOT}/bin/lotse-backup\\n' > /etc/systemd/system/lotse-backup.service
  printf '[Unit]\\nDescription=Daily Lotse database backups\\n\\n[Timer]\\nOnCalendar=*-*-* 03:17:00\\nRandomizedDelaySec=900\\nPersistent=true\\n\\n[Install]\\nWantedBy=timers.target\\n' > /etc/systemd/system/lotse-backup.timer
  systemctl daemon-reload
  systemctl enable --now lotse-backup.timer >/dev/null 2>&1
  echo "backup timer enabled"
else
  echo "backup script installed (no systemd timer)"
fi
`,
    },
  };
}

export async function* runSetupSteps(input: {
  conn: Connection;
  plan: SetupPlan;
  executor: SshExecutor;
  connect: SshConnector;
  settings: SetupSettings;
  signal?: AbortSignal;
}): AsyncGenerator<DeployEvent, Connection, void> {
  const { conn, plan, executor, settings } = input;
  const publicKey = conn.settings.publicKey ?? publicKeyOf(conn.credentials.privateKey as string);
  const scripts = stepScripts(settings, publicKey);
  const todo = plan.steps.filter((s) => s.needed && !s.skipped);
  let done = 0;
  for (const step of plan.steps) {
    if (step.skipped) {
      yield event.log("provision", `Skipping "${step.title}": ${step.skipped}`);
      continue;
    }
    if (!step.needed) {
      yield event.log("provision", `"${step.title}" is already done.`);
      continue;
    }
    if (input.signal?.aborted) throw new LotseError("ABORTED", "The setup was aborted.");
    const entry = scripts[step.id];
    if (!entry) throw new LotseError("INVALID_INPUT", `Unknown setup step "${step.id}".`);
    yield event.progress("provision", ++done, todo.length, step.title);
    const out = await must(executor, `setup-${step.id}`, entry.script, { sudo: true, stdin: entry.stdin, signal: input.signal });
    for (const line of out.trim().split("\n").filter(Boolean)) yield event.log("provision", line, "stdout");
  }

  // From now on everything runs as the deployment user.
  const next: Connection = { ...conn, settings: { ...conn.settings, user: DEPLOY_USER, publicKey } };
  const check = await input.connect(paramsOf(next));
  try {
    await must(check, "verify-deploy-user", "docker info >/dev/null && echo ok");
  } finally {
    check.close();
  }
  yield event.log("provision", `Server is ready. Deployments run as ${DEPLOY_USER}@${conn.settings.host}.`);
  return next;
}
